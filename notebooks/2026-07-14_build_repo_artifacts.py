# Purpose: Stage the 2024 "normal" (noPresel/withPresel) efficiency results for the
#          HLT-diphoton-efficiency-2024-results GitHub repo: csvs, efficiency-vs-pt plots,
#          per-bin fit plots, and a README documenting scope/gaps. No HiggsDNA JSONs and no
#          fullPath variant are staged -- neither exists yet for 2024 (see README for detail).
# Created: 2026-07-14
# Class:   deliverable
# Inputs:  outputs/efficiencies_from_txt.csv, plots/*.{png,pdf},
#          results/HLT_2024_*_SS/passingHLT_*_2024/plots/data_*/{bwDscbCmsFit,bwDscbExpFit}/bin*.png
# Outputs: outputs/repo_staging/{README.md,csvs,efficiency_plots,fit_plots}/...
import re
import shutil
from pathlib import Path

ROOT = Path("/home/santanu/Desktop/HLT_2024_lowmass_final")
STAGE = ROOT / "outputs" / "repo_staging"

LEG_LABEL = {"seed": "seeded", "unseed": "unseeded"}
VARIANT_MAP = {  # matches the naming used in the 2023 repo's fit_plots/ tree
    "bwDscbCmsFit": "sig_bwDscb_bkg_RooCMSShape",
    "bwDscbExpFit": "sig_bwDscb_bkg_Exponential",
}
LEG_RE = re.compile(r"passingHLT_(seed|unseed)_(EB|EE)_(R9.+)_2024$")

README = """\
# HLT diphoton trigger efficiency -- 2024 results

Tag-and-probe trigger efficiency for the CMS diphoton HLT legs, 2024 data, produced the same
way as [HLT-diphoton-efficiency-2023-results](https://github.com/santanumahata/HLT-diphoton-efficiency-2023-results).

## Scope of this repo (as pushed)

- **Eras:** `noPresel_SS` and `withPresel_SS` only, exactly as named in the source tag-and-probe
  output -- no assumption is made that either corresponds to the 2023 repo's `SS`/`fullPath_SS`
  split.
- **`fullPath` variant: not included.** No 2024 fullPath tag-and-probe fits exist yet anywhere on
  the machine this was built on (searched the results directory plus every other 2024-labeled
  workspace on disk). Will be added once those fits are produced.
- **HiggsDNA `TriggerSF` JSONs: not included.** The 2023 repo's JSON step sourced its numbers from
  an external reference CSV rather than the local fits directly, and required hand-picked R9/SCEta
  bin-edge and fallback-mapping choices; that hasn't been redone for 2024 yet.
- **Known gaps in the underlying fits** (not filled in or estimated -- simply absent from the data):
  - `passingHLT_unseed_EB_R9gt0p85_2024` has no fit output in either era.
  - No `unseed_EE_*` bins exist at all for 2024 (present in the 2023 repo).

## Layout

- `csvs/efficiencies_from_txt.csv` -- long-format table: one row per (era, leg, region, R9 bin,
  pt bin, fit variant). Only the `bwDscbCms` (nominal, RooCMSShape background) and `bwDscbExp`
  (alternate, Exponential background) fit variants are populated.
- `efficiency_plots/` -- efficiency vs probe pt, one panel per (era, leg), R9 categories overlaid.
- `fit_plots/<era>/<leg>/<region>_<R9bin>/<bkg model>/bin*.png` -- the individual tag-and-probe
  mass-fit plots that the efficiency numbers were extracted from.

## Reproducing

Generated by `diagnostics/2026-07-14_build_eff_csv_and_plots.ipynb` (CSV + efficiency_plots) and
`diagnostics/2026-07-14_build_repo_artifacts.py` (this staging + fit_plots) in the source workspace.
"""

def stage_csv():
    out_dir = STAGE / "csvs"
    out_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / "outputs" / "efficiencies_from_txt.csv", out_dir / "efficiencies_from_txt.csv")

def stage_efficiency_plots():
    out_dir = STAGE / "efficiency_plots"
    out_dir.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in (ROOT / "plots").glob("*"):
        if f.suffix in (".png", ".pdf"):
            shutil.copy2(f, out_dir / f.name)
            n += 1
    return n

def stage_fit_plots():
    n = 0
    for era_dir in sorted((ROOT / "results").iterdir()):
        if not era_dir.is_dir() or not era_dir.name.startswith("HLT_2024"):
            continue
        era_short = era_dir.name.replace("HLT_2024_", "").replace("_SS", "")  # noPresel / withPresel
        for bin_dir in sorted(era_dir.iterdir()):
            m = LEG_RE.match(bin_dir.name)
            if not m:
                continue
            leg, region, r9bin = m.groups()
            ebin_dir_name = f"{region}_{r9bin}"
            plots_root = bin_dir / "plots"
            if not plots_root.exists():
                continue
            for data_dir in plots_root.iterdir():
                for var_dir in data_dir.iterdir():
                    if var_dir.name not in VARIANT_MAP:
                        continue
                    out_dir = (STAGE / "fit_plots" / era_short / LEG_LABEL[leg]
                               / ebin_dir_name / VARIANT_MAP[var_dir.name])
                    out_dir.mkdir(parents=True, exist_ok=True)
                    for png in sorted(var_dir.glob("bin*.png")):
                        shutil.copy2(png, out_dir / png.name)
                        n += 1
    return n

def main():
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    (STAGE / "README.md").write_text(README)
    stage_csv()
    n_eff = stage_efficiency_plots()
    n_fit = stage_fit_plots()
    print(f"staged csv, {n_eff} efficiency plot files, {n_fit} fit-plot PNGs -> {STAGE}")

if __name__ == "__main__":
    main()
